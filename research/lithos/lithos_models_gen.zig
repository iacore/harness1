/// Writes `text` as a JSON/Zig string literal: wrapped in quotes, with the
/// two bytes that would end it escaped. Ids and owners contain neither, but a
/// generated file must still be valid Zig for any roster.
fn writeLiteral(writer: *std.Io.Writer, text: []const u8) std.Io.Writer.Error!void {
    try writer.writeByte('"');
    for (text) |byte| switch (byte) {
        '"' => try writer.writeAll("\\\""),
        '\\' => try writer.writeAll("\\\\"),
        else => try writer.writeByte(byte),
    };
    try writer.writeByte('"');
}

fn constantName(allocator: std.mem.Allocator, id: []const u8) ![]u8 {
    var buffer: std.ArrayList(u8) = .empty;
    errdefer buffer.deinit(allocator);
    var last_was_separator = false;
    for (id) |byte| {
        if (std.ascii.isAlphanumeric(byte)) {
            try buffer.append(allocator, std.ascii.toLower(byte));
            last_was_separator = false;
        } else if (!last_was_separator and buffer.items.len != 0) {
            try buffer.append(allocator, '_');
            last_was_separator = true;
        }
    }
    while (buffer.items.len != 0 and buffer.items[buffer.items.len - 1] == '_') {
        _ = buffer.pop();
    }
    return buffer.toOwnedSlice(allocator);
}